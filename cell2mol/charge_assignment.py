def check_possible_resonance(charge_state: object, debug: int = 0) -> object:
    prot = charge_state.protonation
    charge_tried = charge_state.uncorr_total_charge
    natoms = prot.natoms

    # Only perform resonance checks for ligands
    # if prot.parent.subtype != "ligand":
    #     if debug >= 2:
    #         print(f"CHECK_POSSIBLE_RESONANCE: Skipping non-ligand type: {prot.parent.subtype}")
    #     return charge_state

    rdkit_obj = charge_state.rdkit_obj
    # coordinating_atoms = [
    #     idx for idx, atom in enumerate(prot.parent.atoms) if atom.mconnec > 0
    # ]
    try:
        possible_res_mols = rdchem.ResonanceMolSupplier(rdkit_obj)
    except Exception as e:
        if debug >= 2:
            print(f"CHECK_POSSIBLE_RESONANCE: Error in ResonanceMolSupplier: {e}")
        return charge_state

    if len(possible_res_mols) == 0:
        return charge_state

    best_res_mol = possible_res_mols[0]
    if best_res_mol is None:
        return charge_state
    # if prot.parent.formula == "H32-C20-N3-O-Si-P":
    #     for i, tmp in enumerate(possible_res_mols):
    #         print(f"CHECK_POSSIBLE_RESONANCE: Found resonance structure {i}: {Chem.MolToSmiles(tmp)} {Chem.MolToSmiles(tmp)==Chem.MolToSmiles(rdkit_obj)}")

    if debug >= 0:
        print(
            f"CHECK_POSSIBLE_RESONANCE: {prot.parent.formula} {len(possible_res_mols)=}"
        )
        print(f"Best candidate: {Chem.MolToSmiles(best_res_mol)}")
        print(f"Original      : {Chem.MolToSmiles(rdkit_obj)}")

    if Chem.MolToSmiles(rdkit_obj) == Chem.MolToSmiles(best_res_mol):
        return charge_state  # No change in resonance

    if debug >= 0:
        print("CHECK_POSSIBLE_RESONANCE: Updating to best resonance structure")

    # Replace molecule and recalculate formal charges
    atom_charges = [a.GetFormalCharge() for a in best_res_mol.GetAtoms()]
    total_charge = sum(atom_charges)
    smiles = Chem.MolToSmiles(best_res_mol)

    if debug >= 2:
        print(f"Updated SMILES: {smiles}")
        print(f"Atom charges  : {atom_charges}")
        print(f"Total charge  : {total_charge}")

    # Verify connectivity
    iscorrect = check_rdkit_obj_connectivity(
        best_res_mol, natoms, charge_tried, debug=debug
    )
    allow = True

    # Construct a new ChargeState object (from_positional is likely a class method)
    ch_state = charge_state.from_positional(
        iscorrect,
        total_charge,
        atom_charges,
        best_res_mol,
        smiles,
        charge_tried,
        allow,
        prot,
    )

    return ch_state


